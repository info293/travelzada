'use client'

/**
 * Package editor, in two tabs:
 *
 *  1. DETAILS — the few things a person fills: name, destination, nights, starting price, main photo,
 *     day-by-day itinerary, stay and guest reviews. When a person writes anything here the package gets
 *     Is_Main: true — shown as one "Main" tag (admins only) in the editor and the package list.
 *  2. AI — overview, highlights, inclusions, FAQs, tags, SEO… written by AI from the details
 *     (POST /api/admin/packages/ai-complete). Only admins see and edit this tab. When a package is saved
 *     without it, the AI fills it automatically first.
 *
 * The package code (e.g. KAS_013) is always generated by the system — nobody types it.
 * Computed on save as before: Duration, Price_Range_INR, the old itinerary text, Slug, Last_Updated…
 *
 * Controlled component: the parent owns `formData` and saving.
 */
import { FormEvent, useEffect, useMemo, useRef, useState } from 'react'
import { AlertCircle, CheckCircle2, ExternalLink, Image as ImageIcon, ListChecks, Loader2, Lock, Pencil, Search, Sparkles, Tag, Type } from 'lucide-react'
import ImageUploader from './ImageUploader'
import { Button, cx, inputClass } from './ui'
import { ChipSelect, Collapsible, FormField, LinesInput, MainTag, RowsEditor, SectionTitle, YesNo, errorInput } from './catalog/fields'
import {
  TAGS,
  applyDerived,
  durationLabel,
  formatIN,
  itineraryRows,
  nextPackageCode,
  packageSiteUrl,
  prefixForDestination,
  slugify,
  slugTyping,
  splitList,
  suggestSeoDescription,
  suggestSeoTitle,
  tagValues,
  toNum,
  validatePackage,
  type FormErrors,
  type TagField,
  type TagSuggestions,
} from './catalog/packageUtils'
import type { DestinationRecord, FaqItem, GuestReview, ItineraryDay, PackageDraft, WhyBookItem } from './catalog/types'
import AiCreatePanel, { AiDraftBanner, type AiCreateResponse } from './catalog/ai/AiCreatePanel'
import { AiImagesPanel, GalleryEditor } from './catalog/ai/AiImagesPanel'
import SeoFixButton from '@/components/admin/seo/SeoFixButton'
import { useAuth } from '@/contexts/AuthContext'
import { staffFetch } from '@/lib/admin/staffFetch'

type AiTabId = 'content' | 'photos' | 'tags' | 'extras' | 'seo'
const AI_TABS: Array<{ id: AiTabId; label: string; icon: typeof Sparkles }> = [
  { id: 'content', label: 'Content', icon: Type },
  { id: 'photos', label: 'More photos', icon: ImageIcon },
  { id: 'tags', label: 'Tags', icon: Tag },
  { id: 'extras', label: 'FAQs & policies', icon: ListChecks },
  { id: 'seo', label: 'SEO', icon: Search },
]

interface AiCompleteResponse {
  patch: PackageDraft
  filled: string[]
  similarity: { max: number; label: string; top: Array<{ id: string; name: string; score: number }> }
  checks: string[]
}

export interface PackageFormProps {
  formData: PackageDraft
  /** Preferred: functional updater for the parent's state */
  setFormData?: (updater: (prev: any) => any) => void
  /** Legacy fallback when setFormData isn't provided */
  handleInputChange?: (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement>) => void
  editingPackage: { id?: string } | null
  onSubmit: (e: FormEvent) => void
  onCancel: () => void
  saving?: boolean
  /** Tag values already used in the catalogue */
  suggestions?: TagSuggestions
  /** Every other package — used for unique code/slug checks and code generation */
  otherPackages?: PackageDraft[]
  /** When given, shows a destination picker that generates the package code and links the package */
  destinations?: DestinationRecord[]
  destinationId?: string
  onDestinationChange?: (id: string) => void
  /** Extra line under the destination picker (e.g. how that destination lists packages) */
  destinationNote?: React.ReactNode
  /** Save error from the parent, shown in the footer */
  error?: string
}

export default function PackageForm({
  formData,
  setFormData,
  handleInputChange,
  editingPackage,
  onSubmit,
  onCancel,
  saving,
  suggestions,
  otherPackages = [],
  destinations,
  destinationId = '',
  onDestinationChange,
  destinationNote,
  error,
}: PackageFormProps) {
  const { isAdmin } = useAuth()
  const [tab, setTab] = useState<'details' | 'ai'>('details')
  const [aiTab, setAiTab] = useState<AiTabId>('content')
  const [errors, setErrors] = useState<FormErrors>({})
  const [aiResult, setAiResult] = useState<AiCreateResponse | null>(null)
  const [filling, setFilling] = useState(false)
  const [fillError, setFillError] = useState('')
  const [fillResult, setFillResult] = useState<AiCompleteResponse | null>(null)
  /** Set after "AI fills the rest" on save: submit once the patched data has reached the parent */
  const [pendingSave, setPendingSave] = useState(false)
  const isNew = !editingPackage?.id
  const f = formData

  const set = (patch: PackageDraft) => {
    if (setFormData) setFormData((prev: PackageDraft) => applyDerived(prev, patch))
    else if (handleInputChange) {
      const next = applyDerived(f, patch)
      Object.keys(next).forEach((name) => {
        const value = (next as any)[name]
        if (value !== (f as any)[name]) handleInputChange({ target: { name, value, type: 'text' } } as any)
      })
    }
    const keys = Object.keys(patch)
    if (keys.some((k) => (errors as any)[k])) setErrors((e) => { const n = { ...e }; keys.forEach((k) => delete (n as any)[k]); return n })
  }

  /** A person typed in the Details tab → this package is tagged "Main" */
  const setD = (patch: PackageDraft) => set({ ...patch, Is_Main: true })

  const str = (k: keyof PackageDraft) => String((f as any)[k] ?? '')
  const tagOpts = (field: TagField) => suggestions?.[field] || TAGS[field].defaults
  const tagValue = (field: TagField) => tagValues(TAGS[field], f[field])
  const setTag = (field: TagField, v: string[]) => set({ [field]: v.join(TAGS[field].joiner || '') } as PackageDraft)
  const setTagD = (field: TagField, v: string[]) => setD({ [field]: v.join(TAGS[field].joiner || '') } as PackageDraft)

  const nights = toNum(f.Duration_Nights)
  const minPrice = toNum(f.Price_Min_INR)
  const days = useMemo(() => itineraryRows(f), [f.Day_Wise_Itinerary_Details, f.Day_Wise_Itinerary]) // eslint-disable-line react-hooks/exhaustive-deps
  const aiWritten = !!str('Overview').trim()

  // ---------- package code: always generated by the system ----------
  const autoCode = useMemo(() => {
    const dest = destinations?.find((d) => d.id === destinationId)
    const prefix = prefixForDestination(dest, otherPackages) || 'PKG'
    return nextPackageCode(prefix, otherPackages)
  }, [destinations, destinationId, otherPackages])
  useEffect(() => {
    if (isNew && autoCode && f.Destination_ID !== autoCode) set({ Destination_ID: autoCode })
  }, [isNew, autoCode]) // eslint-disable-line react-hooks/exhaustive-deps

  // ---------- AI fills the rest ----------
  const fillWithAi = async (overwrite = false): Promise<boolean> => {
    setFilling(true)
    setFillError('')
    try {
      const res = await staffFetch<AiCompleteResponse>('/api/admin/packages/ai-complete', { draft: { ...f, id: editingPackage?.id }, destinationId, overwrite })
      set(res.patch)
      setFillResult(res)
      return true
    } catch (e) {
      setFillError((e as Error).message || 'AI could not fill the package.')
      return false
    } finally {
      setFilling(false)
    }
  }

  // After the AI patch lands in the parent's state, the parent's onSubmit sees it — save then.
  const onSubmitRef = useRef(onSubmit)
  onSubmitRef.current = onSubmit
  useEffect(() => {
    if (!pendingSave || filling) return
    setPendingSave(false)
    onSubmitRef.current({ preventDefault() {} } as FormEvent)
  }, [pendingSave, filling, f])

  const submit = async (e: FormEvent) => {
    e.preventDefault()
    const errs = validatePackage(f, otherPackages)
    delete (errs as any).Price_Max_INR
    delete (errs as any).Destination_ID // generated by the system
    setErrors(errs)
    if (Object.keys(errs).length) {
      if (Object.keys(errs).some((k) => k !== 'Slug')) setTab('details')
      else {
        setTab('ai')
        setAiTab('seo')
      }
      return
    }
    // Nothing written by AI yet → let AI fill the rest first, then save
    if (!aiWritten) {
      const ok = await fillWithAi(false)
      if (ok) setPendingSave(true)
      return
    }
    onSubmit(e)
  }

  /** Fill the form with a whole AI-designed package (keeps any photo already added). Not saved until Create. */
  const applyAiDraft = (res: AiCreateResponse) => {
    const { Gallery_Images, ...draft } = res.draft
    // Designed entirely by AI → not "Main" (it becomes Main as soon as a person edits its details)
    set({ ...draft, Is_Main: false, ...(Array.isArray(f.Gallery_Images) && f.Gallery_Images.length ? {} : { Gallery_Images: Gallery_Images || [] }) })
    if (res.destinationId && res.destinationId !== destinationId) onDestinationChange?.(res.destinationId)
    setErrors({})
    setAiResult(res)
  }

  const setDays = (rows: ItineraryDay[]) => setD({ Day_Wise_Itinerary_Details: rows.map((r, i) => ({ ...r, day: i + 1 })) })
  const errorCount = Object.keys(errors).length
  const detailErrors = Object.keys(errors).filter((k) => k !== 'Slug').length
  const seoTitleSuggestion = suggestSeoTitle(f)
  const slugSuggestion = slugify(str('Destination_Name'))
  const busy = saving || filling

  return (
    <form onSubmit={submit} noValidate className="relative flex min-h-full flex-col">
      <div className="flex-1 space-y-6 pb-6">
        {/* Two tabs: Details (a person fills) · AI (filled automatically, admins only) */}
        {isAdmin && (
          <div className="sticky top-0 z-10 -mx-5 -mt-5 flex items-center justify-between gap-2 border-b border-gray-200 bg-white/95 px-3 py-2 backdrop-blur">
            <div className="flex gap-1">
              {([
                { id: 'details', label: 'Details', icon: Pencil },
                { id: 'ai', label: 'AI', icon: Sparkles },
              ] as const).map((t) => {
                const Icon = t.icon
                const n = t.id === 'details' ? detailErrors : errors.Slug ? 1 : 0
                return (
                  <button
                    key={t.id}
                    type="button"
                    onClick={() => setTab(t.id)}
                    className={cx(
                      'inline-flex items-center gap-1.5 rounded-lg px-4 py-1.5 text-sm font-semibold transition-colors',
                      tab === t.id ? 'bg-bordeaux-50 text-bordeaux-700' : 'text-gray-600 hover:bg-gray-100',
                    )}
                  >
                    <Icon className="h-4 w-4" />
                    {t.label}
                    {t.id === 'ai' && filling && <Loader2 className="h-3.5 w-3.5 animate-spin" />}
                    {n > 0 && <span className="rounded-full bg-red-600 px-1.5 text-[10px] text-white">{n}</span>}
                  </button>
                )
              })}
            </div>
            {f.Is_Main && <span title="A person wrote this package's details"><MainTag /></span>}
          </div>
        )}

        {aiResult && <AiDraftBanner res={aiResult} onDismiss={() => setAiResult(null)} />}
        {isAdmin && isNew && !aiResult && tab === 'details' && (
          <AiCreatePanel destinations={destinations} otherPackages={otherPackages} destinationId={destinationId} onDraft={applyAiDraft} />
        )}

        {/* ================= DETAILS TAB (filled by a person) ================= */}
        {tab === 'details' && (
        <section className="space-y-5">
          <p className="text-xs text-gray-500">
            Fill these — AI writes everything in the <b>AI</b> tab (overview, highlights, FAQs, tags and SEO) when you click {isNew ? 'Create' : 'Save'}.
          </p>

          <FormField label="Package name" required error={errors.Destination_Name} hint="The title customers see, e.g. “Romantic Bali Escape with Private Pool Villa”.">
            <input value={str('Destination_Name')} onChange={(e) => setD({ Destination_Name: e.target.value })} className={errorInput(errors.Destination_Name)} placeholder="Romantic Bali Escape" autoFocus={isNew} />
          </FormField>

          {destinations && (
            <FormField label="Destination" hint={destinationId ? destinationNote : 'Where this trip goes — the package is added to that destination page.'}>
              <select value={destinationId} onChange={(e) => { onDestinationChange?.(e.target.value); setD({}) }} className={inputClass}>
                <option value="">— Choose destination —</option>
                {[...destinations].sort((a, b) => String(a.name).localeCompare(String(b.name))).map((d) => (
                  <option key={d.id} value={d.id}>
                    {d.name}{d.country && d.country !== d.name ? `, ${d.country}` : ''}
                  </option>
                ))}
              </select>
            </FormField>
          )}

          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
            <FormField label="Nights" required error={errors.Duration_Nights} hint={nights ? `Shown as ${durationLabel(nights)}` : 'Days are worked out for you'}>
              <input
                type="number"
                min={1}
                inputMode="numeric"
                value={nights ?? ''}
                onChange={(e) => setD({ Duration_Nights: e.target.value === '' ? (undefined as any) : Number(e.target.value) })}
                className={errorInput(errors.Duration_Nights)}
                placeholder="5"
              />
            </FormField>
            <FormField label="Price from (₹)" required error={errors.Price_Min_INR} hint={minPrice ? `Site shows “From ₹${formatIN(minPrice)}”` : 'Per couple / per person, as you sell it'}>
              <input type="number" min={0} inputMode="numeric" value={minPrice ?? ''} onChange={(e) => setD({ Price_Min_INR: e.target.value === '' ? (undefined as any) : Number(e.target.value) })} className={errorInput(errors.Price_Min_INR)} placeholder="48500" />
            </FormField>
          </div>

          <div>
            <div className="mb-1 flex items-center gap-1.5">
              <span className="text-xs font-semibold text-gray-700">Main photo<span className="ml-0.5 text-bordeaux-600">*</span></span>
            </div>
            <ImageUploader value={str('Primary_Image_URL')} onChange={(url) => setD({ Primary_Image_URL: url })} folder="/packages" />
            <input
              value={str('Primary_Image_URL').startsWith('data:') ? '' : str('Primary_Image_URL')}
              onChange={(e) => setD({ Primary_Image_URL: e.target.value.trim() })}
              className={cx(errorInput(errors.Primary_Image_URL), 'mt-2 text-xs')}
              placeholder="…or paste an image link (https://…)"
            />
            {errors.Primary_Image_URL && (
              <span className="mt-1 flex items-center gap-1 text-xs font-medium text-red-600"><AlertCircle className="h-3.5 w-3.5" />{errors.Primary_Image_URL}</span>
            )}
          </div>

          <div>
            <SectionTitle
              title={"Day-by-day itinerary"}
              description="A title for each day is enough — AI writes the description and activities you leave empty."
              right={
                !days.length && nights ? (
                  <Button type="button" size="sm" variant="secondary" onClick={() => setDays(Array.from({ length: nights + 1 }, (_, i) => ({ day: i + 1, title: i === 0 ? 'Arrival' : i === nights ? 'Departure' : '', description: '', activities: [] })))}>
                    Add {nights + 1} days
                  </Button>
                ) : undefined
              }
            />
            <RowsEditor<ItineraryDay>
              rows={days}
              onChange={setDays}
              empty={() => ({ day: days.length + 1, title: '', description: '', activities: [] })}
              rowTitle={(r, i) => `Day ${i + 1}${r.title ? ` · ${r.title}` : ''}`}
              addLabel="Add day"
              emptyText={nights ? 'No days yet — click “Add days” above, or leave it to AI.' : 'No days yet.'}
              fields={[
                { key: 'title', label: 'Title', placeholder: 'Arrive in Bali & check in' },
                { key: 'description', label: 'Description (optional)', type: 'textarea', placeholder: 'What happens on this day…' },
                { key: 'activities', label: 'Activities, one per line (optional)', type: 'lines', placeholder: 'Airport pickup\nHotel check-in' },
              ]}
            />
          </div>

          <div className="space-y-4 rounded-xl border border-gray-200 p-4">
            <SectionTitle title={"Stay"} />
            <FormField label="Hotel category">
              <ChipSelect value={tagValue('Star_Category')} onChange={(v) => setTagD('Star_Category', v)} options={tagOpts('Star_Category')} />
            </FormField>
            <FormField label="Meal plan">
              <ChipSelect value={tagValue('Meal_Plan')} onChange={(v) => setTagD('Meal_Plan', v)} options={tagOpts('Meal_Plan')} />
            </FormField>
            <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
              <FormField label="Hotels">
                <input value={str('Hotel_Examples')} onChange={(e) => setD({ Hotel_Examples: e.target.value })} className={inputClass} placeholder="The Anvaya Beach Resort, Amadea Resort" />
              </FormField>
              <FormField label="Route / nights split" hint="Shown under the package title">
                <input value={str('Location_Breakup')} onChange={(e) => setD({ Location_Breakup: e.target.value })} className={inputClass} placeholder="3N Seminyak + 2N Ubud" />
              </FormField>
            </div>
          </div>

          <Collapsible
            title={"Guest reviews"}
            description="Optional — real reviews from customers who took this trip."
            count={f.Guest_Reviews?.length}
            defaultOpen={!!f.Guest_Reviews?.length}
          >
            <RowsEditor<GuestReview>
              rows={f.Guest_Reviews || []}
              onChange={(rows) => setD({ Guest_Reviews: rows })}
              empty={() => ({ name: '', content: '', date: '', rating: '5/5' })}
              addLabel="Add review"
              rowTitle={(r, i) => r.name || `Review ${i + 1}`}
              fields={[
                { key: 'name', label: 'Name', span: 3, placeholder: 'Anjali Mehta' },
                { key: 'date', label: 'Date', span: 2, placeholder: '14 November 2025' },
                { key: 'rating', label: 'Rating', span: 1, placeholder: '5/5' },
                { key: 'content', label: 'Review', type: 'textarea' },
              ]}
            />
          </Collapsible>

          <p className="flex items-center gap-1.5 text-xs text-gray-500">
            <Lock className="h-3.5 w-3.5" />
            Package code <span className="rounded bg-gray-100 px-1.5 py-0.5 font-mono font-semibold text-gray-700">{str('Destination_ID') || autoCode}</span>
            — created by the system, always unique.
          </p>
        </section>
        )}

        {/* ================= AI TAB (admins only) ================= */}
        {isAdmin && tab === 'ai' && (
          <section className="space-y-4">
            <div className="flex flex-wrap items-start justify-between gap-3">
              <div>
                <p className="text-xs text-gray-500">
                  {aiWritten ? 'Written from the main details. You can edit anything below.' : 'Empty for now — AI writes it from the main details (or automatically on save).'}
                </p>
              </div>
              <div className="flex flex-wrap gap-2">
                <Button type="button" size="sm" variant={aiWritten ? 'secondary' : 'primary'} onClick={() => fillWithAi(aiWritten)} disabled={busy || !str('Destination_Name').trim()}>
                  {filling ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <Sparkles className="h-3.5 w-3.5" />}
                  {filling ? 'AI is writing…' : aiWritten ? 'Rewrite with AI' : 'Fill the rest with AI'}
                </Button>
                {!isNew && <SeoFixButton draft={f as Record<string, any>} packageId={editingPackage?.id} onApply={(patch) => set(patch as PackageDraft)} />}
              </div>
            </div>

            {fillError && (
              <p className="flex items-center gap-1.5 rounded-lg bg-red-50 px-3 py-2 text-xs text-red-700"><AlertCircle className="h-3.5 w-3.5 shrink-0" />{fillError}</p>
            )}
            {fillResult && !filling && (
              <div className="rounded-lg bg-white px-3 py-2 text-xs text-gray-700 ring-1 ring-gray-200">
                <p className="flex items-center gap-1.5 font-semibold text-emerald-700">
                  <CheckCircle2 className="h-3.5 w-3.5" /> AI filled {fillResult.filled.length} field{fillResult.filled.length === 1 ? '' : 's'} · page is{' '}
                  {fillResult.similarity.label === 'unique' ? 'unique' : `${Math.round(fillResult.similarity.max * 100)}% similar to “${fillResult.similarity.top[0]?.name}”`}
                </p>
                {fillResult.checks.length > 0 && (
                  <ul className="mt-1 list-disc space-y-0.5 pl-5 text-gray-600">
                    {fillResult.checks.map((c, i) => <li key={i}>{c}</li>)}
                  </ul>
                )}
              </div>
            )}

            <div className="flex gap-1 overflow-x-auto border-b border-gray-200">
              {AI_TABS.map((t) => {
                const Icon = t.icon
                return (
                  <button
                    key={t.id}
                    type="button"
                    onClick={() => setAiTab(t.id)}
                    className={cx(
                      '-mb-px inline-flex shrink-0 items-center gap-1.5 border-b-2 px-3 py-2 text-xs font-semibold transition-colors',
                      aiTab === t.id ? 'border-bordeaux-600 text-bordeaux-700' : 'border-transparent text-gray-500 hover:text-gray-800',
                    )}
                  >
                    <Icon className="h-3.5 w-3.5" />
                    {t.label}
                    {t.id === 'seo' && errors.Slug && <span className="rounded-full bg-red-600 px-1.5 text-[10px] text-white">1</span>}
                  </button>
                )
              })}
            </div>

            {aiTab === 'content' && (
              <div className="space-y-4">
                <FormField label="Overview" hint="2–3 short paragraphs. Also used as the Google description if that is empty.">
                  <textarea rows={6} value={str('Overview')} onChange={(e) => set({ Overview: e.target.value })} className={inputClass} placeholder="AI writes this from the main details." />
                </FormField>
                <FormField label="Highlights" hint="One per line">
                  <LinesInput value={Array.isArray(f.Highlights) ? f.Highlights : splitList(f.Highlights)} onChange={(v) => set({ Highlights: v })} rows={5} placeholder={'Sunset dinner cruise\nPrivate pool villa'} />
                </FormField>
                <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
                  <FormField label="Inclusions" hint="One per line">
                    <LinesInput value={splitList(f.Inclusions)} onChange={(v) => set({ Inclusions: v })} rows={6} placeholder={'4★ stay with breakfast\nPrivate airport transfers'} />
                  </FormField>
                  <FormField label="Exclusions" hint="One per line">
                    <LinesInput value={splitList(f.Exclusions)} onChange={(v) => set({ Exclusions: v })} rows={6} placeholder={'Flights\nVisa\nPersonal expenses'} />
                  </FormField>
                </div>
              </div>
            )}

            {aiTab === 'photos' && (
              <div className="space-y-4">
                <AiImagesPanel draft={f} onChange={set} />
                <GalleryEditor draft={f} onChange={set} />
              </div>
            )}

            {aiTab === 'tags' && (
              <div className="space-y-4">
                <p className="text-xs text-gray-500">Tags decide where this package appears: homepage occasion rails, filters and the AI trip planner.</p>
                {(['Occasion', 'Travel_Type', 'Mood', 'Theme', 'Budget_Category'] as TagField[]).map((field) => (
                  <FormField key={field} label={TAGS[field].label} hint={TAGS[field].hint || (TAGS[field].multi ? 'Pick one or more' : 'Pick one')}>
                    <ChipSelect value={tagValue(field)} onChange={(v) => setTag(field, v)} options={tagOpts(field)} multi={TAGS[field].multi} />
                  </FormField>
                ))}
                <Collapsible title="More details for the AI planner" description="Helps the AI planner match the right travellers.">
                  <FormField label="Adventure level">
                    <ChipSelect value={tagValue('Adventure_Level')} onChange={(v) => setTag('Adventure_Level', v)} options={tagOpts('Adventure_Level')} allowCustom={false} />
                  </FormField>
                  <FormField label="Stay type">
                    <ChipSelect value={tagValue('Stay_Type')} onChange={(v) => setTag('Stay_Type', v)} options={tagOpts('Stay_Type')} />
                  </FormField>
                  <div className="flex flex-wrap gap-6">
                    <FormField label="Good for kids"><YesNo value={f.Child_Friendly} onChange={(v) => set({ Child_Friendly: v })} /></FormField>
                    <FormField label="Good for elderly"><YesNo value={f.Elderly_Friendly} onChange={(v) => set({ Elderly_Friendly: v })} /></FormField>
                    <FormField label="Transfers">
                      <ChipSelect value={str('Transfer_Type') ? [str('Transfer_Type')] : []} onChange={(v) => set({ Transfer_Type: v[0] || '' })} options={['Private', 'Shared']} allowCustom={false} />
                    </FormField>
                  </div>
                  <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
                    <FormField label="Best season"><input value={str('Seasonality')} onChange={(e) => set({ Seasonality: e.target.value })} className={inputClass} placeholder="April–October" /></FormField>
                    <FormField label="Group size"><input value={str('Group_Size')} onChange={(e) => set({ Group_Size: e.target.value })} className={inputClass} placeholder="2 Adults" /></FormField>
                    <FormField label="Ideal traveller" className="sm:col-span-2"><input value={str('Ideal_Traveler_Persona')} onChange={(e) => set({ Ideal_Traveler_Persona: e.target.value })} className={inputClass} placeholder="Couples aged 25–35 wanting a private romantic escape" /></FormField>
                    <FormField label="Airport code"><input value={str('Airport_Code')} onChange={(e) => set({ Airport_Code: e.target.value.toUpperCase() })} className={inputClass} placeholder="DPS" /></FormField>
                    <FormField label="Local currency"><input value={str('Currency')} onChange={(e) => set({ Currency: e.target.value.toUpperCase() })} className={inputClass} placeholder="IDR" /></FormField>
                    <FormField label="Language"><input value={str('Language_Preference')} onChange={(e) => set({ Language_Preference: e.target.value })} className={inputClass} placeholder="English" /></FormField>
                    <FormField label="Climate"><input value={str('Climate_Type')} onChange={(e) => set({ Climate_Type: e.target.value })} className={inputClass} placeholder="Tropical" /></FormField>
                    <FormField label="Safety score"><input value={str('Safety_Score')} onChange={(e) => set({ Safety_Score: e.target.value })} className={inputClass} placeholder="8.5/10" /></FormField>
                    <FormField label="Sustainability score"><input value={str('Sustainability_Score')} onChange={(e) => set({ Sustainability_Score: e.target.value })} className={inputClass} placeholder="7/10" /></FormField>
                  </div>
                </Collapsible>
              </div>
            )}

            {aiTab === 'extras' && (
              <div className="space-y-3">
                <p className="text-xs text-gray-500">When a section is empty the package page shows our standard text.</p>
                <Collapsible title="FAQs" count={f.FAQ_Items?.length} defaultOpen={!!f.FAQ_Items?.length}>
                  <RowsEditor<FaqItem>
                    rows={f.FAQ_Items || []}
                    onChange={(rows) => set({ FAQ_Items: rows })}
                    empty={() => ({ question: '', answer: '' })}
                    addLabel="Add question"
                    rowTitle={(r, i) => r.question || `Question ${i + 1}`}
                    fields={[
                      { key: 'question', label: 'Question', placeholder: 'Is breakfast included?' },
                      { key: 'answer', label: 'Answer', type: 'textarea' },
                    ]}
                  />
                </Collapsible>
                <Collapsible title="Why book with us" count={f.Why_Book_With_Us?.length}>
                  <RowsEditor<WhyBookItem>
                    rows={f.Why_Book_With_Us || []}
                    onChange={(rows) => set({ Why_Book_With_Us: rows })}
                    empty={() => ({ label: '', description: '' })}
                    addLabel="Add reason"
                    rowTitle={(r, i) => r.label || `Reason ${i + 1}`}
                    fields={[
                      { key: 'label', label: 'Heading', placeholder: 'Best price guarantee' },
                      { key: 'description', label: 'Description', type: 'textarea' },
                    ]}
                  />
                </Collapsible>
                <Collapsible title="Booking, payment & cancellation policy" count={['booking', 'payment', 'cancellation'].filter((k) => (f.Booking_Policies as any)?.[k]?.length).length}>
                  {(['booking', 'payment', 'cancellation'] as const).map((k) => (
                    <FormField key={k} label={k === 'booking' ? 'Booking terms' : k === 'payment' ? 'Payment' : 'Cancellation'} hint="One per line">
                      <LinesInput
                        rows={3}
                        value={splitList(f.Booking_Policies?.[k], /\r?\n/)}
                        onChange={(v) => set({ Booking_Policies: { ...(f.Booking_Policies || {}), [k]: v } })}
                        placeholder={k === 'booking' ? 'Instant confirmation\nFlexible dates' : k === 'payment' ? 'Pay in 2 instalments\nZero cost EMI' : 'Free cancellation up to 7 days'}
                      />
                    </FormField>
                  ))}
                </Collapsible>
              </div>
            )}

            {aiTab === 'seo' && (
              <div className="space-y-4">
                <FormField
                  label="Web address (slug)"
                  error={errors.Slug}
                  auto={isNew && !str('Slug')}
                  hint={
                    <span className="flex flex-wrap items-center gap-2">
                      <span className="truncate">travelzada.com{packageSiteUrl({ ...f, Slug: str('Slug') || (isNew ? slugSuggestion : '') })}</span>
                      {!str('Slug') && slugSuggestion && (
                        <button type="button" className="font-semibold text-bordeaux-700 hover:underline" onClick={() => set({ Slug: slugSuggestion })}>Use “{slugSuggestion}”</button>
                      )}
                    </span>
                  }
                >
                  <input value={str('Slug')} onChange={(e) => set({ Slug: slugTyping(e.target.value) })}
                    onBlur={() => str('Slug') && set({ Slug: slugify(str('Slug')) })} className={errorInput(errors.Slug)} placeholder={isNew ? `${slugSuggestion || 'made-from-the-name'} (automatic)` : 'Uses the package code if empty'} />
                </FormField>
                <FormField label="Google title" auto={!str('SEO_Title')} hint={!str('SEO_Title') && seoTitleSuggestion ? `If empty we use: “${seoTitleSuggestion}”` : `${str('SEO_Title').length}/60 characters`}>
                  <input value={str('SEO_Title')} onChange={(e) => set({ SEO_Title: e.target.value })} className={inputClass} placeholder={seoTitleSuggestion} />
                </FormField>
                <FormField label="Google description" auto={!str('SEO_Description')} hint={!str('SEO_Description') ? 'If empty we use the first lines of the overview.' : `${str('SEO_Description').length}/155 characters`}>
                  <textarea rows={3} value={str('SEO_Description')} onChange={(e) => set({ SEO_Description: e.target.value })} className={inputClass} placeholder={suggestSeoDescription(f)} />
                </FormField>
                <FormField label="Keywords" hint="Comma separated">
                  <input value={str('SEO_Keywords')} onChange={(e) => set({ SEO_Keywords: e.target.value })} className={inputClass} placeholder="bali honeymoon package, romantic bali holiday" />
                </FormField>
                <Collapsible title="Advanced" description="Rarely needed">
                  <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
                    <FormField label="Photo caption / alt text" className="sm:col-span-2" hint="Shown under the main photo and read by Google Images">
                      <input value={str('Image_Alt_Text')} onChange={(e) => set({ Image_Alt_Text: e.target.value })} className={inputClass} placeholder="Couple at Tanah Lot temple at sunset" />
                    </FormField>
                    <FormField label="Rating"><input value={str('Rating')} onChange={(e) => set({ Rating: e.target.value })} className={inputClass} placeholder="4.8/5" /></FormField>
                    <FormField label="External booking URL"><input value={str('Booking_URL')} onChange={(e) => set({ Booking_URL: e.target.value })} className={inputClass} placeholder="https://…" /></FormField>
                  </div>
                </Collapsible>
              </div>
            )}
          </section>
        )}
        {!isAdmin && (
          <p className="flex items-start gap-2 rounded-xl bg-bordeaux-50/60 px-4 py-3 text-xs text-bordeaux-900">
            <Sparkles className="mt-0.5 h-3.5 w-3.5 shrink-0" />
            That&apos;s all you need. When you click {isNew ? 'Create package' : 'Save'}, AI writes the overview, highlights, inclusions, FAQs, tags and SEO — an admin can review them later.
          </p>
        )}
      </div>

      {/* Footer */}
      <div className="sticky bottom-0 z-10 -mx-5 -mb-5 flex flex-wrap items-center justify-between gap-3 border-t border-gray-200 bg-white px-5 py-3">
        <div className="min-w-0 text-xs">
          {filling ? (
            <span className="flex items-center gap-1.5 font-medium text-bordeaux-700"><Loader2 className="h-3.5 w-3.5 animate-spin" />AI is writing the rest of the package (about a minute)…</span>
          ) : fillError && !aiWritten ? (
            <span className="flex flex-wrap items-center gap-2 font-medium text-red-600">
              <AlertCircle className="h-3.5 w-3.5" />AI could not fill it.
              <button type="button" className="font-semibold text-bordeaux-700 underline" onClick={() => onSubmit({ preventDefault() {} } as FormEvent)}>Save without AI</button>
            </span>
          ) : error && !errorCount ? (
            <span className="flex items-center gap-1 font-medium text-red-600"><AlertCircle className="h-3.5 w-3.5" />{error}</span>
          ) : errorCount ? (
            <span className="flex items-center gap-1 font-medium text-red-600"><AlertCircle className="h-3.5 w-3.5" />Fix {errorCount} thing{errorCount > 1 ? 's' : ''} before saving</span>
          ) : !isNew && (f.Slug || f.Destination_ID) ? (
            <a href={packageSiteUrl(f)} target="_blank" rel="noreferrer" className="inline-flex items-center gap-1 font-semibold text-gray-600 hover:text-bordeaux-700">
              <ExternalLink className="h-3.5 w-3.5" /> View on site
            </a>
          ) : (
            <span className="text-gray-500">Fields marked * are required</span>
          )}
        </div>
        <div className="flex gap-2">
          <Button type="button" variant="secondary" onClick={onCancel} disabled={busy}>Cancel</Button>
          <Button type="submit" loading={busy}>{isNew ? 'Create package' : 'Save changes'}</Button>
        </div>
      </div>
    </form>
  )
}
